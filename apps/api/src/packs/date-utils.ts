/** YYYY-MM-DD for "today" in the given IANA timezone (en-CA locale formats exactly that way). */
export function todayInTimeZone(timeZone: string): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());
}
